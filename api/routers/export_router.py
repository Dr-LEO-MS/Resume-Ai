def _pdf_filename(resume: dict) -> str:
    """A URL/header-safe, human-friendly PDF filename derived from the resume or cover letter."""
    name = (resume.get("personal") or {}).get("fullName") or "Resume"
    doc_type = resume.get("docType") or resume.get("doc_type") or "resume"
    doc_label = "Cover_Letter" if doc_type == "cover_letter" else "Resume"
    import re as _re
    safe = _re.sub(r"[^A-Za-z0-9 _.\-]+", "", name).strip().replace(" ", "_")
    safe = _re.sub(r"_+", "_", safe).strip("_") or "Resume"
    return f"{safe}_{doc_label}.pdf"


