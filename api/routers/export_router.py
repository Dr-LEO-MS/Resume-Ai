def render_html(resume: dict) -> str:
    """Full standalone HTML document for WeasyPrint, with styles.css inlined
    (avoids any relative-path/base_url ambiguity) and real CSS Paged Media
    page numbers if the user enabled them in /customize.

    Page sizing: explicitly set to A4 (210mm x 297mm) with sensible margins
    via @page, and .resume-doc's normal 560px/max-width cap is overridden to
    fill the full printable width. Without this, WeasyPrint's default page
    box and the resume's screen-sized 560px content box left a large blank
    margin and made everything look shrunk relative to the page — this is
    what actually caused the "content appears too small" complaint; it
    wasn't a DPI or scaling-factor bug in WeasyPrint itself.
    """
    try:
        css = STYLES_CSS_PATH.read_text(encoding="utf-8")
    except OSError:
        css = ""

    customization = resume.get("customization") or {}
    pn = customization.get("pageNumbers") or {}
    page_number_css = ""
    if pn.get("enabled"):
        fmt = pn.get("format", "Page {n}")
        # WeasyPrint supports CSS Paged Media counter(page)/counter(pages).
        content_expr = fmt.replace("{n}", '" counter(page) "').replace("{total}", '" counter(pages) "')
        side = {
            "bottom-left": "bottom-left", "bottom-right": "bottom-right",
            "bottom-center": "bottom-center", "top-right": "top-right",
        }.get(pn.get("position", "bottom-center"), "bottom-center")
        page_number_css = f'@{side} {{ content: "{content_expr}"; font-size: 9px; color: #999; }}'
        # The JS-rendered .doc-page-number placeholder is only for the on-screen
        # preview (browsers can't do per-page counters) — hide it in the PDF
        # since the real @page margin box above renders the actual number.

    page_css = f"""
      @page {{
        size: A4;
        margin: 14mm 16mm;
        {page_number_css}
      }}
      body {{ background: #fff; margin: 0; padding: 0; }}
      .resume-doc {{
        box-shadow: none !important;
        margin: 0 !important;
        width: 100% !important;
        max-width: none !important;
        min-height: 0 !important;
      }}
      .doc-page-number {{ display: none; }}
      .doc-entry, section, .doc-header, .skills-category-block {{
        page-break-inside: avoid;
        break-inside: avoid;
      }}
      .doc-section-title {{
        page-break-after: avoid;
        break-after: avoid;
      }}
    """

    body = render_resume_body(resume)
    return f"""<!DOCTYPE html>
<html><head><meta charset="utf-8"><style>{css}\n{page_css}</style></head>
<body>{body}</body></html>"""


