                    dates = " – ".join(filter(None, [e.get("start"), e.get("end")]))
                    degree_line = f"{e.get('degree','')}{', ' + e['field'] if e.get('field') else ''}"
                    head = doc.add_paragraph()
                    head.paragraph_format.space_after = Pt(0)
                    run = head.add_run(degree_line)
                    run.bold = True
                    run.font.name = body_font
                    if dates:
                        tab = head.add_run(f"\t{dates}")
                        tab.italic = True
                    sub = f"{e.get('school','')}{' · GPA ' + e['gpa'] if e.get('gpa') else ''}"
