    p = resume.get("personal") or {}
    cl = resume.get("coverLetter") or resume.get("cover_letter") or {}
    display_name = p.get("fullName") or "Your Name"
    display_title = p.get("title") or p.get("jobTarget") or "Applicant"
    style_attr = _customization_style_vars(resume.get("customization"))
    template_id = resume.get("template", "cl-modern")
    if template_id == "classic":
        template_id = "cl-classic"
    elif template_id == "creative":
        template_id = "cl-creative"
    elif template_id == "executive":
        template_id = "cl-executive"
    elif template_id == "modern" or not template_id.startswith("cl-"):
        template_id = "cl-modern"

    contact_items = []
    if p.get("email"):
        contact_items.append(f'<a href="mailto:{esc(p["email"])}">{esc(p["email"])}</a>')
    phone = (p.get("phone") or "").strip()
    if phone:
        tel = _tel_href(phone)
        if tel:
            contact_items.append(f'<a href="tel:{esc(tel)}">{esc(phone)}</a>')
    loc = p.get("location") or ", ".join(filter(None, [p.get("address"), p.get("city"), p.get("postalCode")]))
    if loc:
        contact_items.append(f'<span>{esc(loc)}</span>')
    if p.get("linkedin"):
        contact_items.append(f'<a href="{esc(_normalize_url(p["linkedin"]))}" target="_blank">{esc(_profile_handle(p["linkedin"]))}</a>')
    if p.get("website"):
        contact_items.append(f'<a href="{esc(_normalize_url(p["website"]))}" target="_blank">{esc(_short_link(p["website"]))}</a>')

