    doc_type = resume.get("docType") or resume.get("doc_type") or "resume"
    doc_label = "Cover_Letter" if doc_type == "cover_letter" else "Resume"
    import re as _re
    safe = _re.sub(r"[^A-Za-z0-9 _.\-]+", "", name).strip().replace(" ", "_")
