    body_font = _first_font_name(fonts.get("body") or "Calibri")
    heading_color = _hex_to_rgbcolor(colors.get("heading") or "", theme_primary)
    accent_color = _hex_to_rgbcolor(colors.get("accent") or "", theme_primary)
    body_color = _hex_to_rgbcolor(colors.get("body") or "", "#222222")
    name_size = Pt(font_sizes.get("name") or 22)
    h2_size = Pt(font_sizes.get("h2") or 12)
    body_size = Pt(font_sizes.get("body") or 10.5)

    doc = Document()

    # ---- Configure standard A4 page dimensions and margins ----
    if doc.sections:
        sec = doc.sections[0]
