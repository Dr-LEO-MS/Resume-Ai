@router.post("/share-link", response_model=schemas.ShareLinkResponse)
def create_share_link(payload: schemas.ExportRequest, db: Session = Depends(get_db)):
    features = settings_service.get_group(db, "features", redact=False)
    if not features.get("sharing_enabled", True):
        raise HTTPException(status_code=403, detail="Public sharing is currently disabled site-wide.")
    slug = uuid.uuid4().hex[:10]
    resume_row = models.Resume(
        owner_id=None,
        name=payload.resume.get("personal", {}).get("fullName", "Untitled"),
        template=payload.resume.get("template", "classic"),
        content=payload.resume,
        is_public=True,
        share_slug=slug,
    )
    db.add(resume_row)
    db.commit()
    return {"url": f"/r/{slug}"}
