def _customization_style_vars(customization: dict | None) -> str:
    if not customization:
        return ""
    f = customization.get("fontSizes") or {}
    c = customization.get("colors") or {}
    fam = customization.get("fonts") or {}
    s = customization.get("spacing") or {}
    vars_ = {
        "--doc-name-size": f"{f['name']}px" if f.get("name") else None,
        "--doc-h2-size": f"{f['h2']}px" if f.get("h2") else None,
        "--doc-body-size": f"{f['body']}px" if f.get("body") else None,
        "--doc-contact-size": f"{f['contact']}px" if f.get("contact") else None,
        "--doc-heading-color": c.get("heading"),
        "--doc-body-color": c.get("body"),
        "--doc-link-color": c.get("link"),
        "--doc-accent-color": c.get("accent"),
        "--doc-heading-font": fam.get("heading"),
        "--doc-body-font": fam.get("body"),
        "--doc-line-height": s.get("lineHeight"),
        "--doc-section-spacing": f"{s['sectionSpacing']}px" if s.get("sectionSpacing") is not None else None,
        "--doc-page-margin": f"{s['pageMargin']}px" if s.get("pageMargin") is not None else None,
    }
    return ";".join(f"{k}:{v}" for k, v in vars_.items() if v not in (None, ""))


def _short_link(url: str, max_len: int = 40) -> str:
    import re as _re
    u = (url or "").strip()
    u = _re.sub(r"^https?://", "", u, flags=_re.IGNORECASE)
    u = _re.sub(r"^www\.", "", u, flags=_re.IGNORECASE).rstrip("/")
    if len(u) > max_len:
        parts = u.split("/")
        u = "/".join(parts[:2]) + "/…"
    return u


def _normalize_url(url: str) -> str:
    u = (url or "").strip()
    if not u:
        return ""
    return u if u.lower().startswith(("http://", "https://")) else "https://" + u


def _profile_handle(url: str) -> str:
    import re as _re
    u = _re.sub(r"^[a-z][a-z0-9+.\-]*://", "", (url or "").strip(), flags=_re.IGNORECASE)
    u = _re.sub(r"^www\.", "", u, flags=_re.IGNORECASE)
    u = _re.sub(r"[?#].*$", "", u).rstrip("/")
    if not u:
        return "@"
    parts = [seg for seg in u.split("/") if seg]
    if len(parts) > 1:
        return "@" + parts[-1]
    host = parts[0].split(".")
    return "@" + (host[-2] if len(host) >= 2 else host[0])


def _tel_href(phone: str) -> str:
    import re as _re
    s = (phone or "").strip()
    if not s:
        return ""
    return ("+" if s.startswith("+") else "") + _re.sub(r"\D", "", s)


def format_markdown_lite(raw: str) -> str:
    """Python mirror of static/js/template-engine.js's formatMarkdownLite() —
    keep both in sync if the syntax changes. Converts **bold**, *italic*,
    __underline__, "- " bullet lines, and [text](url) links into safe HTML.
    Text is escaped first; only these specific patterns are then converted,
    so this can never introduce unescaped content."""
    lines = (raw or "").split("\n")
    html_parts = []
    in_list = False
    link_re = re.compile(r"\[([^\]]+)\]\((https?://[^\s)]+)\)")
    for line in lines:
        is_bullet = bool(re.match(r"^\s*-\s+", line))
        if is_bullet and not in_list:
            html_parts.append('<ul class="doc-formatted-list">')
            in_list = True
        if not is_bullet and in_list:
            html_parts.append("</ul>")
            in_list = False

        content = esc(re.sub(r"^\s*-\s+", "", line) if is_bullet else line)
        content = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", content)
        content = re.sub(r"__(.+?)__", r"<u>\1</u>", content)
        content = re.sub(r"\*(.+?)\*", r"<em>\1</em>", content)
        content = link_re.sub(r'<a href="\2" target="_blank" rel="noopener noreferrer" title="\1">\1</a>', content)

        html_parts.append(f"<li>{content}</li>" if is_bullet else (f"<p>{content}</p>" if content else ""))
    if in_list:
        html_parts.append("</ul>")
    return "".join(html_parts)


def _render_contact(p: dict) -> str:
    parts = []
    if p.get("email"):
        parts.append(f'<a href="mailto:{esc(p["email"])}" title="Send an email to {esc(p["email"])}" aria-label="Email {esc(p["email"])}">{esc(p["email"])}</a>')
    phone = (p.get("phone") or "").strip()
    if phone:
        tel = _tel_href(phone)
        if tel:
            parts.append(f'<a href="tel:{esc(tel)}" title="Call {esc(phone)}" aria-label="Call phone number {esc(phone)}">{esc(phone)}</a>')
    if p.get("location"):
        parts.append(f"<span>{esc(p['location'])}</span>")
    # Professional links: @handle label, clickable underlying URL
    for key, aria in (("linkedin", "View LinkedIn profile"), ("github", "View GitHub profile"), ("website", "Visit portfolio website")):
        url = (p.get(key) or "").strip()
        if url:
            href = esc(_normalize_url(url))
            parts.append(f'<a href="{href}" target="_blank" rel="noopener noreferrer" title="{aria}" aria-label="{aria}">{esc(_profile_handle(url))}</a>')
    return "".join(parts)


def _render_photo(customization: dict | None) -> str:
    photo = (customization or {}).get("photo") or {}
    if not photo.get("visible") or not photo.get("url"):
        return ""
    shape_class = "doc-photo-square" if photo.get("shape") == "square" else "doc-photo-circle"
    return f'<img class="doc-photo {shape_class}" src="{esc(photo["url"])}" alt="Profile photo">'


def _render_page_number(customization: dict | None) -> str:
    pn = (customization or {}).get("pageNumbers") or {}
    if not pn.get("enabled"):
        return ""
    position = pn.get("position", "bottom-center")
    fmt = pn.get("format", "Page {n}")
    return f'<div class="doc-page-number doc-page-number-{position}" data-page-format="{esc(fmt)}"></div>'


def _get_sec_title(section_id: str, default_title: str, resume: dict) -> str:
    section_titles = resume.get("sectionTitles") or {}
    if section_id in section_titles and section_titles[section_id]:
        return str(section_titles[section_id])
    sec_data = resume.get(section_id)
    if isinstance(sec_data, dict) and sec_data.get("title"):
        return str(sec_data["title"])
    return default_title


def _render_skills(skills, resume: dict = None) -> str:
    if not skills:
        return ""
    title = _get_sec_title("skills", "Skills", resume or {})
    if isinstance(skills, list):
        if not skills:
            return ""
        pills = "".join(f'<span class="skill-pill">{esc(s)}</span>' for s in skills)
        return f'<section><div class="doc-section-title">{esc(title)}</div><div class="skills-wrapper">{pills}</div></section>'

    categories = [("technical", "Technical Skills"), ("tools", "Tools & Technologies"), ("soft", "Soft Skills & Leadership")]
    blocks = []
    for key, label in categories:
        items = skills.get(key) or []
        if not items:
            continue
        pills = "".join(f'<span class="skill-pill">{esc(s)}</span>' for s in items)
        blocks.append(
            f'<div class="skills-category-block"><strong style="font-size:11px;color:#888;display:block;margin-bottom:3px">{label}</strong>'
            f'<div class="skills-wrapper">{pills}</div></div>'
        )
    if not blocks:
        return ""
    return f'<section><div class="doc-section-title">{esc(title)}</div>{"".join(blocks)}</section>'


def _render_section(section_id: str, resume: dict) -> str:
    if section_id in (resume.get("hiddenSections") or []):
        return ""

    if section_id == "summary":
        if not resume.get("summary"):
            return ""
        title = _get_sec_title("summary", "Profile Summary", resume)
        return f'<section><div class="doc-section-title">{esc(title)}</div>{format_markdown_lite(resume["summary"])}</section>'

    if section_id == "experience":
        entries = resume.get("experience") or []
        if not entries:
            return ""
        title = _get_sec_title("experience", "Experience", resume)
        bullet_style = ((resume.get("customization") or {}).get("spacing") or {}).get("bulletStyle", "disc")
        bullet_class = f"bullets-{bullet_style}"
        rows = []
        for e in entries:
            dates = " – ".join(filter(None, [e.get("start"), ("Present" if e.get("current") else e.get("end"))]))
            head_title = esc(e.get("role", "")) + (f" — {esc(e.get('company', ''))}" if e.get("company") else "")
            loc = f'<div class="doc-entry-sub">{esc(e["location"])}</div>' if e.get("location") else ""
            bullets = "".join(f"<li>{esc(b)}</li>" for b in (e.get("bullets") or []) if b)
            rows.append(
                f'<div class="doc-entry"><div class="doc-entry-head"><span>{head_title}</span><span>{esc(dates)}</span></div>'
                f'{loc}<ul class="doc-bullets {bullet_class}">{bullets}</ul></div>'
            )
        return f'<section><div class="doc-section-title">{esc(title)}</div>{"".join(rows)}</section>'

    if section_id == "education":
        entries = resume.get("education") or []
        if not entries:
            return ""
        title = _get_sec_title("education", "Education", resume)
        rows = []
        for e in entries:
            dates = " – ".join(filter(None, [e.get("start"), e.get("end")]))
            degree = esc(e.get("degree", "")) + (f", {esc(e['field'])}" if e.get("field") else "")
            sub = esc(e.get("school", "")) + (f" · GPA {esc(e['gpa'])}" if e.get("gpa") else "")
            honors = f'<div class="doc-entry-details"><strong>Honors:</strong> {esc(e["honors"])}</div>' if e.get("honors") else ""
            coursework = f'<div class="doc-entry-details"><strong>Coursework:</strong> {esc(e["coursework"])}</div>' if e.get("coursework") else ""
            rows.append(
                f'<div class="doc-entry"><div class="doc-entry-head"><span>{degree}</span><span>{esc(dates)}</span></div>'
                f'<div class="doc-entry-sub">{sub}</div>{honors}{coursework}</div>'
            )
        return f'<section><div class="doc-section-title">{esc(title)}</div>{"".join(rows)}</section>'

    if section_id == "skills":
        return _render_skills(resume.get("skills"), resume)

    if section_id == "projects":
        entries = resume.get("projects") or []
        if not entries:
            return ""
        title = _get_sec_title("projects", "Projects", resume)
        rows = []
        for p in entries:
            name = esc(p.get("name", ""))
            role = (f" ({esc(p['role'])})" if p.get("role") else "")
            link = p.get("link") or ""
            if link:
                href = esc(_normalize_url(link))
                head = f'<a class="project-title-link" href="{href}" target="_blank" rel="noopener noreferrer" title="View project: {name}" aria-label="View project {name}">{name}</a>{role}'
            else:
                head = name + role
            desc = f'<div class="doc-entry-sub">{esc(p["description"])}</div>' if p.get("description") else ""
            rows.append(f'<div class="doc-entry"><div class="doc-entry-head"><span>{head}</span></div>{desc}</div>')
        return f'<section><div class="doc-section-title">{esc(title)}</div>{"".join(rows)}</section>'

    if section_id == "certifications":
        entries = resume.get("certifications") or []
        if not entries:
            return ""
        title = _get_sec_title("certifications", "Certifications", resume)
        rows = "".join(
            f'<div class="doc-entry-sub"><strong>{esc(c.get("name",""))}</strong>'
            f'{" — " + esc(c["issuer"]) if c.get("issuer") else ""}{" (" + esc(c["date"]) + ")" if c.get("date") else ""}</div>'
            for c in entries
        )
        return f'<section><div class="doc-section-title">{esc(title)}</div>{rows}</section>'

    if section_id == "languages":
        entries = resume.get("languages") or []
        if not entries:
            return ""
        title = _get_sec_title("languages", "Languages", resume)
        pills = "".join(f'<span class="skill-pill">{esc(l.get("name",""))} · {esc(l.get("level",""))}</span>' for l in entries)
        return f'<section><div class="doc-section-title">{esc(title)}</div><div class="skills-wrapper">{pills}</div></section>'

    if section_id == "power_statement":
        stmt = resume.get("power_statement")
        if not stmt:
            return ""
        title = _get_sec_title("power_statement", "Power Statement", resume)
        return f'<section><div class="doc-section-title">{esc(title)}</div><div class="doc-entry-sub" style="font-weight:500; font-size:1.05em;">{format_markdown_lite(stmt)}</div></section>'

    if section_id == "hobbies":
        entries = resume.get("hobbies") or []
        if not entries:
            return ""
        title = _get_sec_title("hobbies", "Hobbies & Interests", resume)
        hobbies_list = entries if isinstance(entries, list) else [entries]
        pills = "".join(f'<span class="skill-pill">{esc(h.get("name", "") if isinstance(h, dict) else h)}</span>' for h in hobbies_list)
        return f'<section><div class="doc-section-title">{esc(title)}</div><div>{pills}</div></section>'

    if section_id == "references":
        entries = resume.get("references") or []
        if not entries:
            return ""
        title = _get_sec_title("references", "References", resume)
        rows = []
        for r in entries:
            name_title = esc(r.get("name", "")) + (f" — {esc(r['title'])}" if r.get("title") else "")
            comp = f'<span>{esc(r["company"])}</span>' if r.get("company") else ""
            contact = f'<div class="doc-entry-sub">{esc(r["contact"])}</div>' if r.get("contact") else ""
            rows.append(f'<div class="doc-entry"><div class="doc-entry-head"><span>{name_title}</span>{comp}</div>{contact}</div>')
        return f'<section><div class="doc-section-title">{esc(title)}</div>{"".join(rows)}</section>'

    # Generic or custom sections
    sec_data = resume.get(section_id)
    if not sec_data:
        return ""
    fallback_title = section_id.replace("custom_section_", "Custom Section ").replace("_", " ").title()
    title = _get_sec_title(section_id, fallback_title, resume)

    if isinstance(sec_data, str):
        return f'<section><div class="doc-section-title">{esc(title)}</div>{format_markdown_lite(sec_data)}</section>'

    items = sec_data if isinstance(sec_data, list) else (sec_data.get("items") if isinstance(sec_data, dict) and isinstance(sec_data.get("items"), list) else [])
    if items:
        rows = []
        for item in items:
            main_title = item.get("title") or item.get("name") or item.get("role") or item.get("activity") or ""
            sub_title = item.get("city") or item.get("location") or item.get("subtitle") or item.get("organization") or item.get("issuer") or item.get("company") or ""
            start = item.get("start") or item.get("date")
            end = item.get("end")
            date_str = f"{start}{' – ' + end if end else ''}" if start else ""
            head = f'<span><strong>{esc(main_title)}</strong>{(" — " + esc(sub_title)) if sub_title else ""}</span>{f"<span>{esc(date_str)}</span>" if date_str else ""}'
            desc = f'<div class="doc-entry-sub">{format_markdown_lite(item["description"])}</div>' if item.get("description") else ""
            rows.append(f'<div class="doc-entry"><div class="doc-entry-head">{head}</div>{desc}</div>')
        return f'<section><div class="doc-section-title">{esc(title)}</div>{"".join(rows)}</section>'

    return ""


